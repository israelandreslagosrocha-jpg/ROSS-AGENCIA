import assert from 'node:assert/strict';
import vm from 'node:vm';
import {readFile} from 'node:fs/promises';
const links=[];
const ctx={window:{location:{search:'?utm_source=instagram&utm_campaign=queule_2026&email=private%40example.com',href:'https://rossagencia.cl/',origin:'https://rossagencia.cl'}},URL,URLSearchParams,document:{querySelectorAll:()=>links}};
for(const href of ['eventos-corporativos.html','https://www.passline.com/eventos/example','mailto:contacto@rossagencia.cl','#cotiza','privacidad.html','https://wa.me/56920159948?text=Hola']) links.push({getAttribute:()=>href,href});
vm.runInNewContext(await readFile('site/attribution.js','utf8'),ctx);
const read=ctx.window.ROSS_ATTRIBUTION.read;
assert.equal(read('?utm_source=facebook&utm_campaign=evento_2026').utm_source,'facebook');
for(const search of ['?utm_source=name%40example.com','?utm_source=56912345678','?utm_source=https://x.com','?utm_source='+ 'a'.repeat(81)]) assert.equal(Object.keys(read(search)).length,0);
assert.ok(links[0].href.includes('utm_source=instagram'));
assert.ok(!links[0].href.includes('email='));
assert.equal(links[1].href,'https://www.passline.com/eventos/example');
assert.equal(links[2].href,'mailto:contacto@rossagencia.cl');
assert.equal(links[3].href,'#cotiza');
assert.equal(links[4].href,'privacidad.html');
assert.ok(new URL(links[5].href).searchParams.get('text').includes('utm_source: instagram'));
assert.ok(new URL(links[5].href).searchParams.get('text').startsWith('Hola'));
vm.runInNewContext(await readFile('site/quote.js','utf8'),ctx);
const msg=new URL(ctx.window.ROSS_QUOTE.build(new Map([['nombre','QA'],['tipo','otro'],['mensaje','Prueba']]),read(ctx.window.location.search))).searchParams.get('text');
assert.ok(msg.includes('utm_source: instagram'));assert.ok(!msg.includes('private'));
assert.ok(!ctx.window.ROSS_QUOTE.build(new Map([['nombre','QA'],['tipo','otro'],['mensaje','Prueba']])).includes('utm_'));
console.log('UTM: lectura permitida, exclusión de datos ajenos, navegación interna y referencia WhatsApp verificadas; sin atribución inventada.');
